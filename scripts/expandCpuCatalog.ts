export function runExpansion() {
  const cpusPath = path.resolve(process.cwd(), 'server/data/buildcores/cpus.json');
  const metadataPath = path.resolve(process.cwd(), 'server/data/buildcores/metadata.json');

  const existingCpus: any[] = JSON.parse(fs.readFileSync(cpusPath, 'utf8'));
  console.log(`CPUs existentes en cpus.json: ${existingCpus.length}`);

  const existingNames = new Set(existingCpus.map(c => c.name.toLowerCase().trim()));
  const existingIds = new Set(existingCpus.map(c => c.id));

  let addedCount = 0;
  const toAdd: any[] = [];

  for (const cpu of GENERATIONAL_CPUS) {
    const cleanName = cpu.name.toLowerCase().trim();
    if (!existingNames.has(cleanName) && !existingIds.has(cpu.id)) {
      toAdd.push(cpu);
      existingNames.add(cleanName);
      existingIds.add(cpu.id);
      addedCount++;
    }
  }

  console.log(`Se agregarán ${addedCount} nuevos procesadores de todas las generaciones.`);

  const merged = [...existingCpus, ...toAdd];
  fs.writeFileSync(cpusPath, JSON.stringify(merged, null, 2), 'utf8');

  // Update metadata
  const metadata = JSON.parse(fs.readFileSync(metadataPath, 'utf8'));
  metadata.counts.cpus = merged.length;
  metadata.counts.total = (metadata.counts.total || 0) + addedCount;
  metadata.synchronizedAt = new Date().toISOString();
  fs.writeFileSync(metadataPath, JSON.stringify(metadata, null, 2), 'utf8');

  console.log(`cpus.json actualizado con éxito. Total actual: ${merged.length} procesadores.`);
}

runExpansion();
